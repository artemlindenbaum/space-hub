/// Явный контракт: как получить баланс.
/// Фичи могут зависеть только от этого интерфейса, не зная реализацию.
abstract class BalancePort {
  /// Текущий баланс (например, для мгновенной проверки).
  double get balance;

  /// Реактивные обновления баланса (для UI).
  Stream<double> balanceStream();
}
